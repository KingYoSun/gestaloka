import type pg from "pg";
import type { z } from "zod";
import type { PlayCommand } from "@gestaloka/contracts";
import { AccessError } from "../http/access.js";
import type { WorldContext } from "../world/store.js";

type Db = Pick<pg.Pool, "query">;
export type TeamCommand = Extract<
  z.infer<typeof PlayCommand>,
  { command: `team-${string}` }
>;

type TeamMember = {
  actor_id: string;
  team_id: string;
  place_id: string | null;
  pending: boolean;
};

export class PlayTeams {
  async setup(db: Db) {
    await db.query(`CREATE TABLE IF NOT EXISTS bot_team_member (
      world_id uuid NOT NULL REFERENCES world_construction(id),
      actor_id uuid NOT NULL, team_id uuid NOT NULL,
      place_id uuid, arrival bigint GENERATED BY DEFAULT AS IDENTITY,
      pending boolean NOT NULL DEFAULT false, PRIMARY KEY(world_id,actor_id));
      CREATE INDEX IF NOT EXISTS bot_team_members ON bot_team_member(world_id,team_id,arrival);
      CREATE TABLE IF NOT EXISTS bot_team_invite (
      world_id uuid NOT NULL REFERENCES world_construction(id),
      actor_id uuid NOT NULL, team_id uuid NOT NULL, inviter_id uuid NOT NULL,
      PRIMARY KEY(world_id,actor_id,team_id));`);
  }

  async members(db: Db, world: string, actors: string[]) {
    return (
      await db.query<TeamMember>(
        "SELECT * FROM bot_team_member WHERE world_id=$1 AND actor_id=ANY($2::uuid[]) ORDER BY arrival",
        [world, actors],
      )
    ).rows;
  }

  async team(db: Db, world: string, team: string) {
    return (
      await db.query<TeamMember & { session_id: string | null }>(
        `SELECT m.*, s.session_id FROM bot_team_member m LEFT JOIN bot_scene s
       ON s.world_id=m.world_id AND s.actor_id=m.actor_id AND NOT s.closed
       WHERE m.world_id=$1 AND m.team_id=$2 ORDER BY m.arrival`,
        [world, team],
      )
    ).rows;
  }

  async arrived(db: Db, world: string, actor: string, place: string | null) {
    await db.query(
      "UPDATE bot_team_member SET place_id=$3,arrival=DEFAULT WHERE world_id=$1 AND actor_id=$2",
      [world, actor, place],
    );
  }

  async pending(db: Db, world: string, actor: string, waiting: boolean) {
    await db.query(
      "UPDATE bot_team_member SET pending=$3 WHERE world_id=$1 AND actor_id=$2 AND pending IS DISTINCT FROM $3",
      [world, actor, waiting],
    );
  }

  async command(
    db: Db,
    world: string,
    context: WorldContext,
    actor: string,
    input: TeamCommand,
    place: string | null,
  ) {
    const [membership] = await this.members(db, world, [actor]);
    let teamId = membership?.team_id;
    let message = "チームの状態を取得しました";
    switch (input.command) {
      case "team-invite": {
        if (
          input.targetId === actor ||
          !(
            await db.query(
              `SELECT 1 FROM world_access a JOIN world_subject s ON s.id=a.subject_id AND s.active
           JOIN app_user u ON u.id=s.user_id AND NOT u.banned
           WHERE a.construction_id=$1 AND a.actor_id=$2 AND a.role='player'`,
              [world, input.targetId],
            )
          ).rowCount
        )
          throw new AccessError(
            409,
            "TEAM_TARGET_UNAVAILABLE",
            "同じ世界の別のプレイヤーを指定してください",
          );
        if ((await this.members(db, world, [input.targetId])).length)
          throw new AccessError(
            409,
            "TEAM_ALREADY_JOINED",
            "招待先はすでにチームに所属しています",
          );
        if (!teamId) {
          teamId = input.requestId;
          await db.query(
            "INSERT INTO bot_team_member(world_id,actor_id,team_id,place_id) VALUES($1,$2,$3,$4)",
            [world, actor, teamId, place],
          );
        }
        await db.query(
          "INSERT INTO bot_team_invite VALUES($1,$2,$3,$4) ON CONFLICT DO NOTHING",
          [world, input.targetId, teamId, actor],
        );
        message = "チームに招待しました";
        break;
      }
      case "team-join": {
        if (teamId && teamId !== input.teamId)
          throw new AccessError(
            409,
            "TEAM_ALREADY_JOINED",
            "現在のチームから離脱してから加入してください",
          );
        if (!teamId) {
          const invite = await db.query(
            "SELECT 1 FROM bot_team_invite WHERE world_id=$1 AND actor_id=$2 AND team_id=$3",
            [world, actor, input.teamId],
          );
          if (!invite.rowCount)
            throw new AccessError(
              409,
              "TEAM_INVITE_REQUIRED",
              "本人に届いたチームの招待を指定してください",
            );
          teamId = input.teamId;
          await db.query(
            "INSERT INTO bot_team_member(world_id,actor_id,team_id,place_id,pending) VALUES($1,$2,$3,$4,true)",
            [world, actor, teamId, place],
          );
          await db.query(
            "DELETE FROM bot_team_invite WHERE world_id=$1 AND actor_id=$2",
            [world, actor],
          );
        }
        message = "チームに加入しました";
        break;
      }
      case "team-leave":
        await db.query(
          "DELETE FROM bot_team_invite WHERE world_id=$1 AND inviter_id=$2",
          [world, actor],
        );
        await db.query(
          "DELETE FROM bot_team_member WHERE world_id=$1 AND actor_id=$2",
          [world, actor],
        );
        teamId = undefined;
        message = "チームから離脱しました";
        break;
    }
    const person = async (actorId: string) => ({
      actorId,
      name: (await context.node(actorId))?.text ?? "人物",
    });
    const invites = (
      await db.query<{ team_id: string; inviter_id: string }>(
        "SELECT team_id,inviter_id FROM bot_team_invite WHERE world_id=$1 AND actor_id=$2 ORDER BY team_id",
        [world, actor],
      )
    ).rows;
    return {
      team: teamId
        ? {
            teamId,
            members: await Promise.all(
              (await this.team(db, world, teamId)).map((member) =>
                person(member.actor_id),
              ),
            ),
          }
        : null,
      invitations: await Promise.all(
        invites.map(async (invite) => ({
          teamId: invite.team_id,
          inviter: await person(invite.inviter_id),
        })),
      ),
      action: { command: input.command, message },
    };
  }
}
